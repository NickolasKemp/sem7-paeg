import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Вміст звіту до лабораторної роботи описано декларативно (блоками),
 * щоб одні й ті самі дані рендерились і у .docx, і у .pdf.
 * Вставки коду беруться безпосередньо з вихідних файлів — звіт не розходиться з реалізацією.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Витягує фрагмент коду: від рядка з міткою (разом з коментарем над ним)
 * до закриваючої дужки на тому самому рівні вкладеності.
 */
export function extract(file: string, marker: string): string {
  const lines = readFileSync(join(root, file), "utf8").split("\n");
  const start = lines.findIndex((line) => line.includes(marker));
  if (start < 0) throw new Error(`Не знайдено «${marker}» у ${file}`);

  const indent = /^\s*/.exec(lines[start] ?? "")?.[0] ?? "";
  let from = start;
  while (from > 0 && /^\s*(\/\*\*|\*|\*\/|\/\/)/.test(lines[from - 1] ?? "")) from -= 1;

  let end = start;
  while (end < lines.length && lines[end] !== `${indent}}`) end += 1;

  return lines
    .slice(from, end + 1)
    .join("\n")
    .replace(new RegExp(`^${indent}`, "gm"), "");
}

